#Напишите программу, которая запрашивает
#у пользователя ввод числа и выводит на экран все
#числа от 1 до введенного числа включительно.

num = int(input("Введите целое число: "))

if num > 1:
    for i in range(1, num + 1):
        print(i)
else:
    j = 1
    while j >= num:
        print(j)
        j -= 1